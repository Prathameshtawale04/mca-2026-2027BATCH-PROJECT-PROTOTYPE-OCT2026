import math
import re
from collections import Counter
from language_models.ngram_models import DEFAULT_CORPUS

class MultinomialWordModel:
    """
    Multinomial Distribution Model over words in an Information Retrieval corpus.
    In IR, documents are modeled as samples drawn from a multinomial distribution over vocabulary V:
    P(D | theta) = (N! / prod(c(w)!)) * prod( P(w)^c(w) )
    """
    def __init__(self, corpus_text: str = None):
        self.corpus = corpus_text or DEFAULT_CORPUS
        self.word_counts = Counter()
        self.total_words = 0
        self.probabilities = {}
        self._fit()

    def _tokenize(self, text: str):
        return re.findall(r'[a-zA-Z0-9]+', text.lower())

    def _fit(self):
        tokens = self._tokenize(self.corpus)
        self.word_counts = Counter(tokens)
        self.total_words = len(tokens)
        self.probabilities = {
            w: count / self.total_words
            for w, count in self.word_counts.items()
        }

    def get_distribution(self, top_k: int = 25):
        """
        Returns top-K words with their frequency and probability formatted for Chart.js
        """
        most_common = self.word_counts.most_common(top_k)
        labels = [w for w, _ in most_common]
        frequencies = [count for _, count in most_common]
        probs = [round(self.probabilities[w], 5) for w in labels]

        return {
            "total_vocabulary": len(self.probabilities),
            "total_tokens": self.total_words,
            "chart_data": {
                "labels": labels,
                "frequencies": frequencies,
                "probabilities": probs
            },
            "table": [
                {
                    "word": w,
                    "frequency": count,
                    "probability": round(self.probabilities[w], 6),
                    "percentage": f"{self.probabilities[w] * 100:.2f}%"
                }
                for w, count in most_common
            ]
        }

    def score_document(self, text: str):
        """
        Computes the log-likelihood of text being generated by this multinomial distribution:
        log P(D) = sum( c(w) * log P(w) )
        """
        tokens = self._tokenize(text)
        if not tokens:
            return 0.0

        log_likelihood = 0.0
        # Add-1 Laplace smoothing probability floor for unseen words
        p_floor = 1.0 / (self.total_words + len(self.probabilities) + 1)
        
        for w in tokens:
            p = self.probabilities.get(w, p_floor)
            log_likelihood += math.log(p)

        return {
            "token_count": len(tokens),
            "log_likelihood": round(log_likelihood, 4),
            "normalized_likelihood": round(log_likelihood / len(tokens), 4)
        }
